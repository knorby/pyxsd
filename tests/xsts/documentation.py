#: Publication order; explicit so no mapping insertion order is consulted.
PROFILE_ORDER = ("xsd11", "xsd10")

#: Public labels for the two profiles.
PROFILE_LABELS = {"xsd11": "XSD 1.1", "xsd10": "XSD 1.0"}

#: The engines each profile publishes, as an exact set.  XSD 1.1 records
#: pyxsd and the xmlschema comparison engine; XSD 1.0 records pyxsd only.
#: Publication enforces this contract from the recorded results, never from
#: metadata alone, so rewriting ``engines`` cannot legitimise a baseline
#: whose engine data is incomplete.
PROFILE_ENGINES = {
    "xsd11": frozenset({"pyxsd", "xmlschema"}),
    "xsd10": frozenset({"pyxsd"}),
}

#: Test-kind order used by every table.
KIND_ORDER = ("schema", "instance")

#: Published scope: the pinned main suite only.
MAIN_SUITE = "suite.xml"

#: Relative locations consumed by the documentation build and CI.
XSTS_DIR = Path("tests/xsts")
RESULTS_RELATIVE = Path("docs/generated/xsts-results.md")
HEADLINE_RELATIVE = Path("docs/generated/xsts-headline.md")

#: Never rendered in the docs, but records how the fragments were produced.
SOURCE_COMMENT = "<!-- generated by: uv run python tests/report_xsts_docs.py -->"

#: The canonical Task 2 metadata fields, in the order a baseline stores them.
PROVENANCE_FIELDS = (
    "profile",
    "suite_file",
    "case_count",
    "complete",
    "engines",
    "timeout_seconds",
    "jobs",
    "command",
    "source_revision",
    "corpus_revision",
    "python_version",
    "platform",
    "engine_versions",
    "run_completed_at",
)

#: Fields a legacy baseline may carry without claiming a recorded full run.
LEGACY_FIELDS = frozenset({"profile", "case_count"})

#: Relation order for the cross-profile table.
RELATION_ORDER = (
    INVALID_IN_1_0_VALID_IN_1_1,
    SAME_VALID,
    VALID_IN_1_0_INVALID_IN_1_1,
    SAME_INVALID,
    NOT_COMPARABLE,
)


class PublicationError(Exception):
    """Raised when checked-in data cannot be published as a full run."""


def format_agreement(passed: int, checked: int) -> str:
    """The raw checked-case agreement percentage, never an adjusted rate."""
    if checked == 0:
        return "n/a"
    return f"{100 * passed / checked:.4f}%"


@dataclass(frozen=True)
class _Profile:
    """One profile's baseline, cases, reconstructed results, and summary."""

    name: str
    baseline: Baseline
    cases: Mapping[str, Case]
    results: tuple[CaseResult, ...]
    summary: Summary
    provenance: Mapping[str, object] | None

    @property
    def label(self) -> str:
        return _profile_label(self.name)

    @property
    def engines(self) -> tuple[str, ...]:
        return tuple(sorted({result.engine for result in self.results}))


@dataclass(frozen=True)
class _Model:
    """Everything both fragments render, loaded once and read-only."""

    profiles: tuple[_Profile, ...]
    dispositions: tuple[Disposition, ...]
    cases_by_profile: Mapping[str, Mapping[str, Case]]
    baselines: Mapping[str, Baseline]
    unclassified: Mapping[str, tuple[str, ...]]


def _profile_label(name: str) -> str:
    return PROFILE_LABELS[name]


def _profile(model: _Model, name: str) -> _Profile:
    return next(data for data in model.profiles if data.name == name)


def _split_baseline_key(profile: str, key: str) -> tuple[str, str, str]:
    """Split ``engine:test:kind`` without assuming test IDs are colon-free."""
    parts = key.split(":")
    if len(parts) < 3 or not all(parts):
        raise PublicationError(
            f"{profile} baseline key {key!r} is malformed; expected engine:test:kind"
        )
    return parts[0], ":".join(parts[1:-1]), parts[-1]


def _baseline_results(
    profile: str,
    baseline: Baseline,
    cases: Mapping[str, Case],
) -> tuple[CaseResult, ...]:
    """Reconstruct Task 1 results from baseline keys in canonical order.

    Expected and actual verdicts exist only to derive failure direction; an
    outcome is never rewritten and a non-Boolean expectation yields no
    direction.  Keys for cases outside the main suite, or with a mismatched
    kind, are publication errors so an extra-suite case cannot leak into the
    denominator.
    """
    results: list[CaseResult] = []
    for key in sorted(baseline.results):
        engine, test_id, kind = _split_baseline_key(profile, key)
        case = cases.get(test_id)
        if case is None:
            raise PublicationError(
                f"{profile} baseline records {test_id!r}, which is not in the main "
                f"{MAIN_SUITE} suite"
            )
        if case.kind != kind:
            raise PublicationError(
                f"{profile} baseline key {key!r} records kind {kind!r} for a {case.kind!r} case"
            )
        value = baseline.results[key]
        try:
            outcome = Outcome(value)
        except ValueError as exc:
            raise PublicationError(
                f"{profile} baseline key {key!r} has unknown outcome {value!r}"
            ) from exc
        expected_valid = case.expected_valid
        actual: bool | None = None
        if expected_valid is not None:
            if outcome is Outcome.PASS:
                actual = expected_valid
            elif outcome is Outcome.FAIL:
                actual = not expected_valid
        results.append(
            CaseResult(
                test_id=test_id,
                set_name=case.set_name,
                contributor=case.contributor,
                group_name=case.group_name,
                kind=kind,
                engine=engine,
                outcome=outcome,
                expected=case.expected_validity,
                actual=actual,
            )
        )
    return tuple(results)


def _require_engine_coverage(
    profile: str,
    results: tuple[CaseResult, ...],
    cases: Mapping[str, Case],
) -> None:
    """Enforce the per-profile engine contract over the recorded results.

    Publication requires exactly the engines :data:`PROFILE_ENGINES` names
    and, for each of them, the exact emitted ``{engine:test_id:kind}`` set:
    one result per main-suite case.  The contract is checked against the
    results, not the metadata, and applies to legacy and full-provenance
    baselines alike, so deleting an engine's results -- or dropping every
    xmlschema entry and rewriting ``engines`` to match -- is a publication
    error rather than a smaller denominator.  Keys outside the emitted set
    cannot reach this check, because ``_baseline_results`` already rejects
    unknown cases and mismatched kinds for every engine; exact set equality
    therefore reduces to the engine contract plus the missing-key
    comparison below.
    """
    required = PROFILE_ENGINES[profile]
    recorded = {result.engine for result in results}
    missing = sorted(required - recorded)
    if missing:
        raise PublicationError(
            f"{profile} baseline records no {', '.join(missing)} results; "
            f"publication requires exactly {', '.join(sorted(required))}"
        )
    unexpected = sorted(recorded - required)
    if unexpected:
        raise PublicationError(
            f"{profile} baseline records results for unexpected engine "
            f"{', '.join(unexpected)}; publication requires exactly "
            f"{', '.join(sorted(required))}"
        )
    for engine in sorted(required):
        emitted = {f"{engine}:{case.test_id}:{case.kind}" for case in cases.values()}
        recorded_keys = {result.key for result in results if result.engine == engine}
        absent = sorted(emitted - recorded_keys)
        if absent:
            raise PublicationError(
                f"{profile} baseline is missing {len(absent)} of {len(emitted)} "
                f"{engine} results for the main {MAIN_SUITE} run, e.g. {absent[0]!r}"
            )


def _publication_provenance(
    profile: str,
    meta: Mapping[str, object],
    case_count: int,
    engines: Sequence[str],
) -> Mapping[str, object] | None:
    """Validated full-run metadata, or ``None`` for a legacy baseline.

    Partial runs, contradictory metadata, and incomplete provenance are
    rejected instead of being rendered as if they came from one full run.
    """
    if "profile" in meta and meta["profile"] != profile:
        raise PublicationError(
            f"{profile} baseline profile metadata is {meta['profile']!r}, expected {profile!r}"
        )
    if "case_count" in meta:
        value = meta["case_count"]
        if isinstance(value, bool) or not isinstance(value, int):
            raise PublicationError(f"{profile} baseline case_count must be an integer")
        if value != case_count:
            raise PublicationError(
                f"{profile} baseline case_count {value} does not match "
                f"{case_count} main-suite cases"
            )
    complete = meta.get("complete")
    if complete is not None and not isinstance(complete, bool):
        raise PublicationError(f"{profile} baseline field 'complete' must be a boolean")
    if complete is False:
        raise PublicationError(
            f"{profile} baseline is marked complete = false; partial baselines cannot be published"
        )

    recorded = [
        field for field in PROVENANCE_FIELDS if field not in LEGACY_FIELDS and field in meta
    ]
    if not recorded:
        return None
    missing = [field for field in PROVENANCE_FIELDS if field not in meta]
    if missing:
        raise PublicationError(
            f"{profile} baseline provenance is incomplete; missing: {', '.join(missing)}"
        )
    suite_file = meta["suite_file"]
    if suite_file != MAIN_SUITE:
        raise PublicationError(
            f"{profile} baseline suite_file is {suite_file!r}; "
            f"only the main {MAIN_SUITE} may be published"
        )
    listed = meta["engines"]
    if not isinstance(listed, list) or not all(isinstance(item, str) for item in listed):
        raise PublicationError(f"{profile} baseline engines must be a list of strings")
    if sorted(listed) != sorted(engines):
        raise PublicationError(
            f"{profile} baseline engine metadata {listed!r} does not match "
            f"recorded engines {list(engines)!r}"
        )
    return {field: meta[field] for field in PROVENANCE_FIELDS}


def _load_model(repo_root: Path) -> _Model:
    """Load both profiles, the main catalogue, and reviewed dispositions."""
    root = Path(repo_root)
    catalog = load_catalog(PurePosixPath(str(root / XSTS_DIR / "corpus")), MAIN_SUITE)

    profiles: list[_Profile] = []
    cases_by_profile: dict[str, Mapping[str, Case]] = {}
    baselines: dict[str, Baseline] = {}
    for name in PROFILE_ORDER:
        cases = {case.test_id: case for case in build_cases(catalog, PROFILES[name])}
        baseline = load_baseline(root / XSTS_DIR / f"baseline-{name}.toml")
        results = _baseline_results(name, baseline, cases)
        _require_engine_coverage(name, results, cases)
        engines = tuple(sorted({result.engine for result in results}))
        provenance = _publication_provenance(name, baseline.meta, len(cases), engines)
        profiles.append(
            _Profile(
                name=name,
                baseline=baseline,
                cases=cases,
                results=results,
                summary=summarize(list(results)),
                provenance=provenance,
            )
        )
        cases_by_profile[name] = cases
        baselines[name] = baseline

    dispositions = load_dispositions(root / XSTS_DIR / "dispositions.toml")
    validate_dispositions(dispositions, baselines, cases_by_profile)
    return _Model(
        profiles=tuple(profiles),
        dispositions=dispositions,
        cases_by_profile=cases_by_profile,
        baselines=baselines,
        unclassified=unclassified_failures(dispositions, baselines),
    )


# --------------------------------------------------------------------- tables


def _cell(value: object) -> str:
    """A single Markdown table cell, safe for pipes and newlines."""
    return str(value).replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")


def _table(
    headers: Sequence[object], rows: Sequence[Sequence[object]], aligns: Sequence[str]
) -> list[str]:
    lines = [
        "| " + " | ".join(_cell(header) for header in headers) + " |",
        "|" + "|".join(aligns) + "|",
    ]
    lines.extend("| " + " | ".join(_cell(cell) for cell in row) + " |" for row in rows)
    return lines


def _count(value: int) -> str:
    """Thousands-separated counts keep large denominators readable."""
    return f"{value:,}"


def _format_metadata(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return ", ".join(str(item) for item in value)
    return str(value)


def _engine_columns(model: _Model) -> list[tuple[_Profile, EngineSummary]]:
    columns: list[tuple[_Profile, EngineSummary]] = []
    for data in model.profiles:
        for engine in data.engines:
            columns.append((data, data.summary.engines[engine]))
    return columns


# ---------------------------------------------------------------- selection


def _checked_ids(data: _Profile) -> set[str]:
    return {
        result.test_id
        for result in data.results
        if result.engine == "pyxsd" and result.outcome in CHECKED
    }


def _failing_ids(data: _Profile) -> tuple[str, ...]:
    return tuple(
        sorted(
            {
                result.test_id
                for result in data.results
                if result.engine == "pyxsd" and result.outcome is Outcome.FAIL
            }
        )
    )


def _relation(model: _Model, test_id: str) -> str:
    return expectation_relation(
        model.cases_by_profile["xsd10"][test_id],
        model.cases_by_profile["xsd11"][test_id],
    )


def _other_status(model: _Model, test_id: str, profile: str) -> str:
    """How the other profile records *test_id*: pass, fail, or not checked."""
    case = model.cases_by_profile[profile][test_id]
    value = model.baselines[profile].results.get(f"pyxsd:{test_id}:{case.kind}")
    if value == Outcome.PASS.value:
        return "pass"
    if value == Outcome.FAIL.value:
        return "fail"
    return "not-checked"


def _direction_counts(failures: Sequence[CaseResult]) -> Counter[str]:
    """Reuse the Task 1 direction rules for an arbitrary failure subset."""
    return EngineSummary(engine="", failures=list(failures)).failure_directions()


# --------------------------------------------------------------- rendering


def _render_source(model: _Model) -> list[str]:
    rows = [
        [
            data.label,
            f"{XSTS_DIR.as_posix()}/baseline-{data.name}.toml",
            MAIN_SUITE,
            f"{len(data.cases):,}",
        ]
        for data in model.profiles
    ]
    lines = [
        "## Source data",
        "",
        "Both checked-in baselines and the pinned main `suite.xml` are source",
        "data. The optional `extra-suite.xml` is not part of any denominator on",
        "this page.",
        "",
    ]
    lines.extend(_table(["Profile", "Baseline", "Suite file", "Cases"], rows, [":--"] * 4))
    lines.extend(
        [
            "",
            "Timestamps, revisions, versions, and commands below are read from",
            "baseline metadata, never from the generation time.",
            "",
        ]
    )
    for data in model.profiles:
        lines.extend([f"### {data.label}", ""])
        if data.provenance is None:
            lines.extend(["full-run provenance not recorded", ""])
            continue
        rows = [[field, _format_metadata(data.provenance[field])] for field in PROVENANCE_FIELDS]
        lines.extend(_table(["Field", "Value"], rows, [":--", ":--"]))
        lines.append("")
    return lines


def _render_outcomes(model: _Model) -> list[str]:
    columns = _engine_columns(model)
    headers = ["Outcome"] + [f"{data.label} {engine.engine}" for data, engine in columns]
    rows: list[list[object]] = []
    for outcome in Outcome:
        rows.append(
            [outcome.value] + [_count(engine.outcomes[outcome.value]) for _, engine in columns]
        )
    rows.append(["**Total**"] + [_count(engine.total) for _, engine in columns])
    rows.append(["**Checked (pass + fail)**"] + [_count(engine.checked) for _, engine in columns])
    rows.append(
        ["**Agreement on checked**"]
        + [format_agreement(engine.passed, engine.checked) for _, engine in columns]
    )
    return [
        "## Outcomes and checked agreement",
        "",
        "Counts are per profile and engine. Only `pass` and `fail` are checked",
        "verdicts; every other outcome is outside the checked denominator.",
        "",
        *_table(headers, rows, [":--"] + ["--:"] * len(columns)),
        "",
    ]


def _render_kinds(model: _Model) -> list[str]:
    rows: list[list[object]] = []
    for data in model.profiles:
        for engine_name in data.engines:
            engine = data.summary.engines[engine_name]
            for kind in KIND_ORDER:
                counts = engine.by_kind.get(kind, Counter())
                passed = counts[Outcome.PASS.value]
                failed = counts[Outcome.FAIL.value]
                checked = passed + failed
                rows.append(
                    [
                        data.label,
                        engine_name,
                        kind,
                        _count(sum(counts.values())),
                        _count(passed),
                        _count(failed),
                        _count(checked),
                        format_agreement(passed, checked),
                    ]
                )
    return [
        "## Schema and instance splits",
        "",
        "Cases and checked verdicts within each emitted test kind.",
        "",
        *_table(
            ["Profile", "Engine", "Kind", "Cases", "pass", "fail", "Checked", "Agreement"],
            rows,
            [":--", ":--", ":--", "--:", "--:", "--:", "--:", "--:"],
        ),
        "",
    ]


def _render_directions(model: _Model) -> list[str]:
    rows: list[list[object]] = []
    for data in model.profiles:
        for engine_name in data.engines:
            engine = data.summary.engines[engine_name]
            for kind in KIND_ORDER:
                failures = [failure for failure in engine.failures if failure.kind == kind]
                directions = _direction_counts(failures)
                rows.append(
                    [
                        data.label,
                        engine_name,
                        kind,
                        _count(directions["false-accept"]),
                        _count(directions["false-reject"]),
                        _count(len(failures) - sum(directions.values())),
                        _count(len(failures)),
                    ]
                )
            directions = engine.failure_directions()
            rows.append(
                [
                    data.label,
                    engine_name,
                    "**Total**",
                    _count(directions["false-accept"]),
                    _count(directions["false-reject"]),
                    _count(engine.failed - sum(directions.values())),
                    _count(engine.failed),
                ]
            )
    return [
        "## Failure directions",
        "",
        "A false accept is an observed valid verdict where the corpus expects",
        "invalid; a false reject is the opposite. Direction comes only from the",
        "corpus expectation and the observed verdict, never from a disposition.",
        "",
        *_table(
            [
                "Profile",
                "Engine",
                "Kind",
                "False accepts",
                "False rejects",
                "No direction",
                "Failures",
            ],
            rows,
            [":--", ":--", ":--", "--:", "--:", "--:", "--:"],
        ),
        "",
    ]


def _render_combined(model: _Model) -> list[str]:
    data11 = _profile(model, "xsd11")
    data10 = _profile(model, "xsd10")
    checked11 = _checked_ids(data11)
    checked10 = _checked_ids(data10)
    every = checked11 | checked10
    rows = [
        ["Checked in both profiles", _count(len(checked11 & checked10))],
        ["Checked only in XSD 1.1", _count(len(checked11 - checked10))],
        ["Checked only in XSD 1.0", _count(len(checked10 - checked11))],
        ["Checked in at least one profile", _count(len(every))],
        ["Checked in neither profile", _count(len(data11.cases) - len(every))],
        ["Total main-suite cases", _count(len(data11.cases))],
    ]
    return [
        "## Combined-profile applicability",
        "",
        "Counts are for pyxsd across the two profiles. A case is checked when",
        "its pyxsd outcome is `pass` or `fail`; a non-verdict outcome or a case",
        "outside the main suite is not checked.",
        "",
        *_table(["Category", "Cases"], rows, [":--", "--:"]),
        "",
    ]


def _render_relations(model: _Model) -> list[str]:
    data10 = _profile(model, "xsd10")
    counts: Counter[tuple[str, str]] = Counter()
    for test_id in _failing_ids(data10):
        counts[(_relation(model, test_id), _other_status(model, test_id, "xsd11"))] += 1
    rows: list[list[object]] = []
    for relation in RELATION_ORDER:
        passed = counts[(relation, "pass")]
        failed = counts[(relation, "fail")]
        not_checked = counts[(relation, "not-checked")]
        total = passed + failed + not_checked
        if total:
            rows.append([relation, passed, failed, not_checked, total])
    total_pass = sum(counts[(relation, "pass")] for relation in RELATION_ORDER)
    total_fail = sum(counts[(relation, "fail")] for relation in RELATION_ORDER)
    total_not_checked = sum(counts[(relation, "not-checked")] for relation in RELATION_ORDER)
    total = total_pass + total_fail + total_not_checked
    rows.append(
        [
            "**Total**",
            f"**{total_pass}**",
            f"**{total_fail}**",
            f"**{total_not_checked}**",
            f"**{total}**",
        ]
    )
    classification = _disposition_map(model.dispositions)
    split_rows = [
        [
            test_id,
            data10.cases[test_id].kind,
            (
                classification[(data10.name, test_id)].id
                if (data10.name, test_id) in classification
                else "unclassified"
            ),
        ]
        for test_id in _failing_ids(data10)
        if _relation(model, test_id) == INVALID_IN_1_0_VALID_IN_1_1
        and _other_status(model, test_id, "xsd11") == "pass"
    ]
    return [
        "## Cross-profile failure relationships",
        "",
        "This view covers the checked pyxsd failures in XSD 1.0. The relation",
        "comes from each profile's selected corpus expectations, never from an",
        "outcome.",
        "",
        f"Of the {total} checked XSD 1.0 failures, {total_pass} pass under XSD 1.1, "
        f"{total_fail} fail, and {total_not_checked} are not checked.",
        "",
        *_table(
            ["Relation", "Pass in 1.1", "Fail in 1.1", "Not checked", "Total"],
            rows,
            [":--", "--:", "--:", "--:", "--:"],
        ),
        "",
        "### Intentional version-split failures",
        "",
        f"This view lists {len(split_rows)} checked XSD 1.0 failures with a corpus",
        "expectation that is invalid under XSD 1.0, valid under XSD 1.1, and a",
        "passing XSD 1.1 outcome. They remain raw failures, not accepted passes,",
        "and are candidates for version-specific implementation work.",
        "Same-expectation cases are never included here merely because their",
        "outcomes differ across profiles.",
        "",
        *_table(
            ["Case", "Kind", "Disposition"],
            split_rows,
            [":--", ":--", ":--"],
        ),
        "",
    ]


def _disposition_map(
    dispositions: Sequence[Disposition],
) -> dict[tuple[str, str], Disposition]:
    mapping: dict[tuple[str, str], Disposition] = {}
    for entry in dispositions:
        for profile in entry.profiles:
            for case_id in entry.cases:
                mapping[(profile, case_id)] = entry
    return mapping


def _profile_list(profiles: Sequence[str]) -> str:
    return ", ".join(_profile_label(name) for name in PROFILE_ORDER if name in profiles)


def _render_residuals(model: _Model) -> list[str]:
    dispositions = _disposition_map(model.dispositions)
    failures_by_profile = {data.name: _failing_ids(data) for data in model.profiles}
    summary_rows: list[list[object]] = []
    for data in model.profiles:
        failures = failures_by_profile[data.name]
        unclassified = len(model.unclassified[data.name])
        summary_rows.append([data.label, len(failures), len(failures) - unclassified, unclassified])
    entry_rows: list[list[object]] = []
    for entry in sorted(model.dispositions, key=lambda item: item.id):
        active_profiles = tuple(
            data.name
            for data in model.profiles
            if data.name in entry.profiles
            and any(case_id in failures_by_profile[data.name] for case_id in entry.cases)
        )
        if not active_profiles:
            continue
        active_cases = sum(
            case_id in failures_by_profile[profile]
            for profile in active_profiles
            for case_id in entry.cases
        )
        entry_rows.append(
            [
                entry.id,
                entry.category,
                _profile_list(active_profiles),
                active_cases,
                entry.title,
            ]
        )
    census_rows: list[list[object]] = []
    for data in model.profiles:
        for test_id in _failing_ids(data):
            entry = dispositions.get((data.name, test_id))
            census_rows.append(
                [
                    data.label,
                    test_id,
                    data.cases[test_id].kind,
                    Outcome.FAIL.value,
                    _relation(model, test_id),
                    entry.id if entry is not None else "unclassified",
                ]
            )
    return [
        "## Residual dispositions",
        "",
        "Dispositions are reviewed metadata. They never change `pass`, `fail`,",
        "or the checked denominator, and no adjusted agreement rate is computed",
        "from them. Entries and case counts below include only current failures;",
        "a case that starts passing leaves this view without a disposition edit.",
        "",
        *_table(
            ["Profile", "Checked failures", "Classified", "Unclassified"],
            summary_rows,
            [":--", "--:", "--:", "--:"],
        ),
        "",
        "### Reviewed disposition entries",
        "",
        *_table(
            ["ID", "Category", "Profiles", "Cases", "Title"],
            entry_rows,
            [":--", ":--", ":--", "--:", ":--"],
        ),
        "",
        "### Failure census",
        "",
        "Every checked pyxsd failure appears below with its observed outcome,",
        "corpus expectation relation, and disposition. `unclassified` means no",
        "reviewed disposition claims the case.",
        "",
        *_table(
            ["Profile", "Case", "Kind", "Observed", "Expectation relation", "Disposition"],
            census_rows,
            [":--", ":--", ":--", ":--", ":--", ":--"],
        ),
        "",
    ]


def _render_results(model: _Model) -> str:
    lines = [
        ":orphan:",
        "",
        SOURCE_COMMENT,
        "",
        "Results below are generated from the pinned main `suite.xml` corpus",
        "and the checked-in pyxsd baselines. The optional `extra-suite.xml` is",
        "outside every denominator on this page. A checked case is `pass + fail`;",
        "agreement on checked cases is `100 * pass / (pass + fail)`, with no",
        "adjustment for dispositions and no combined XSD 1.0/1.1 rate.",
        "",
    ]
    lines.extend(_render_source(model))
    lines.extend(_render_outcomes(model))
    lines.extend(_render_kinds(model))
    lines.extend(_render_directions(model))
    lines.extend(_render_combined(model))
    lines.extend(_render_relations(model))
    lines.extend(_render_residuals(model))
    return "\n".join(lines).rstrip("\n") + "\n"


def _render_headline(model: _Model) -> str:
    rows: list[list[object]] = []
    for data in model.profiles:
        engine = data.summary.engines["pyxsd"]
        rows.append(
            [
                data.label,
                f"{engine.passed:,}",
                f"{engine.checked:,}",
                format_agreement(engine.passed, engine.checked),
            ]
        )
    lines = [
        ":orphan:",
        "",
        SOURCE_COMMENT,
        "",
        "Raw checked-case agreement for pyxsd against the pinned main `suite.xml`",
        "corpus:",
        "",
        *_table(
            ["Profile", "Passed", "Checked", "Agreement on checked"],
            rows,
            [":--", "--:", "--:", "--:"],
        ),
        "",
        "Checked cases are `pass + fail`; agreement is `100 * pass / (pass + fail)`.",
        "Main-suite cases only: `extra-suite.xml` is excluded, and no combined",
        "XSD 1.0/1.1 rate is reported. See",
        "[XSTS methodology and residuals](xsts.md).",
    ]
    return "\n".join(lines).rstrip("\n") + "\n"


def build_results_fragment(repo_root: Path) -> str:
    """Render the detailed, deterministic MyST results fragment."""
    return _render_results(_load_model(repo_root))


def build_headline_fragment(repo_root: Path) -> str:
    """Render the short, deterministic MyST headline fragment."""
    return _render_headline(_load_model(repo_root))


def build_fragments(repo_root: Path) -> tuple[tuple[Path, str], ...]:
    """Both publication targets with their content, loaded only once."""
    root = Path(repo_root)
    model = _load_model(root)
    return (
        (root / RESULTS_RELATIVE, _render_results(model)),
        (root / HEADLINE_RELATIVE, _render_headline(model)),
    )

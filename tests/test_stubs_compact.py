"""The compact formatter emits the agent-oriented view of a schema.

The compact view shares the full renderer's member model but is a
description, not importable Python (``ast.parse`` is not required of
it): a two-line header (provenance and an alias legend naming the pyxsd
class each alias stands for), one line per class and per member,
facet-only simple types folded onto the members that use them, and one
trailing comment line listing the root elements. These tests pin the
shape, the aliasing fidelity, and the size target; the full mode's
golden (``test_stubs_full.py``) guards the other direction.
"""

import io

from pyxsd.schema import Schema
from pyxsd.stubs import emit_stub

ORDERS = """<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema">
  <xs:simpleType name="SKU"><xs:restriction base="xs:string">
    <xs:pattern value="\\d{3}-[A-Z]{2}"/>
  </xs:restriction></xs:simpleType>
  <xs:complexType name="Item"><xs:sequence>
    <xs:element name="sku" type="SKU"/>
    <xs:element name="quantity" type="xs:int"/>
    <xs:element name="note" type="xs:string" minOccurs="0"/>
  </xs:sequence>
  <xs:attribute name="id" type="xs:string" use="required"/>
  </xs:complexType>
  <xs:element name="orders"><xs:complexType><xs:sequence>
    <xs:element name="item" type="Item" maxOccurs="unbounded"/>
  </xs:sequence></xs:complexType></xs:element>
</xs:schema>"""


def test_compact_renders_core_shape():
    text = emit_stub(Schema.compile(io.StringIO(ORDERS)), compact=True)
    assert "class Item:" in text
    assert "quantity: int" in text  # aliased from Int
    assert "note: str | None" in text
    assert "item: list[Item]" in text
    assert "# pattern: \\d{3}-[A-Z]{2}" in text  # simple type inlined onto sku


def test_compact_has_no_docstrings_or_imports():
    text = emit_stub(Schema.compile(io.StringIO(ORDERS)), compact=True)
    assert '"""' not in text
    assert "\nimport " not in text and not text.startswith("import ")
    assert "from pyxsd" not in text


def test_compact_is_much_smaller_than_xsd():
    xsd = ORDERS
    text = emit_stub(Schema.compile(io.StringIO(xsd)), compact=True)
    assert len(text) < len(xsd) // 2


def test_compact_is_much_smaller_than_the_full_stub():
    schema = Schema.compile(io.StringIO(ORDERS))
    full = emit_stub(schema)
    compact = emit_stub(schema, compact=True)
    assert len(compact) < len(full) // 2


def test_compact_header_is_provenance_plus_alias_legend():
    text = emit_stub(Schema.compile(io.StringIO(ORDERS)), compact=True)
    lines = text.splitlines()
    assert lines[0].startswith("# Generated by pyxsd")
    assert "compact" in lines[0]
    assert lines[1].startswith("# aliases: ")
    # The legend names the pyxsd class each alias stands for.
    assert "str=String" in lines[1]
    assert "int=Int" in lines[1]
    assert lines[2] == ""  # header ends after the two comment lines


def test_compact_annotations_only_use_legend_spellings():
    # Fidelity rule: every name a member annotation uses is either a
    # rendered class or a legend alias; the full-mode spellings (Int,
    # String) and the dropped simple type (SKU) appear nowhere in the
    # body.
    text = emit_stub(Schema.compile(io.StringIO(ORDERS)), compact=True)
    body = "\n".join(text.splitlines()[2:])
    assert "Int" not in body
    assert "String" not in body
    assert "SKU" not in body


def test_compact_folds_facet_only_simple_types_onto_their_members():
    text = emit_stub(Schema.compile(io.StringIO(ORDERS)), compact=True)
    assert "class SKU" not in text
    assert "sku: str  # pattern: \\d{3}-[A-Z]{2}" in text


def test_compact_roots_are_a_single_trailing_line():
    text = emit_stub(Schema.compile(io.StringIO(ORDERS)), compact=True)
    assert text.rstrip("\n").splitlines()[-1] == "# roots: orders: Orders"


def test_compact_legend_names_every_class_an_alias_folds():
    # One alias may stand for several pyxsd classes; the legend names
    # each of them, so the spelling stays mappable.
    xsd = """<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema">
      <xs:complexType name="rec"><xs:sequence>
        <xs:element name="a" type="xs:string"/></xs:sequence>
        <xs:attribute name="b" type="xs:ID"/>
      </xs:complexType>
      <xs:element name="root" type="rec"/>
    </xs:schema>"""
    text = emit_stub(Schema.compile(io.StringIO(xsd)), compact=True)
    assert "# aliases: str=String+ID" in text


def test_compact_omits_documentation():
    xsd = """<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema">
      <xs:complexType name="itemType">
        <xs:annotation><xs:documentation>An item in the inventory.</xs:documentation></xs:annotation>
        <xs:sequence><xs:element name="name" type="xs:string"/></xs:sequence>
      </xs:complexType>
      <xs:element name="root" type="itemType"/>
    </xs:schema>"""
    text = emit_stub(Schema.compile(io.StringIO(xsd)), compact=True)
    assert "An item in the inventory." not in text
    assert "class itemType:" in text
    assert "name: str" in text


def test_compact_keeps_inheritance_on_the_class_line():
    xsd = """<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema">
      <xs:complexType name="base"><xs:sequence>
        <xs:element name="a" type="xs:string"/></xs:sequence></xs:complexType>
      <xs:complexType name="derived"><xs:complexContent><xs:extension base="base">
        <xs:sequence><xs:element name="b" type="xs:int"/></xs:sequence>
      </xs:extension></xs:complexContent></xs:complexType>
      <xs:element name="root" type="derived"/>
    </xs:schema>"""
    text = emit_stub(Schema.compile(io.StringIO(xsd)), compact=True)
    assert "class base:" in text
    assert "class derived(base):" in text


def test_compact_keeps_a_list_simple_type_with_its_item_type():
    # A list type's content is its item type, not facet comments: it
    # keeps a one-line class of its own so ``list[intList]`` still
    # resolves.
    xsd = """<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema">
      <xs:simpleType name="intList"><xs:list itemType="xs:int"/></xs:simpleType>
      <xs:complexType name="bag"><xs:sequence>
        <xs:element name="runs" type="intList" maxOccurs="unbounded"/>
      </xs:sequence></xs:complexType>
      <xs:element name="root" type="bag"/>
    </xs:schema>"""
    text = emit_stub(Schema.compile(io.StringIO(xsd)), compact=True)
    assert "class intList(TypeList): ..." in text
    assert "runs: list[intList]" in text


def test_compact_renders_extension_members_as_one_liners(tmp_path):
    overlay = tmp_path / "overlay.py"
    overlay.write_text(
        "from pyxsd.schema_base import SchemaBase\n\n"
        "class Item(SchemaBase):\n"
        "    name = 'Item'\n"
        "    @property\n"
        "    def label(self) -> str:\n"
        "        return 'x'\n"
        "    def double(self, count: int) -> str:\n"
        "        return 'x' * count\n"
    )
    schema = Schema.compile(io.StringIO(ORDERS), overlay=overlay)
    text = emit_stub(schema, compact=True)
    assert "label: str" in text
    assert "def double(self, count: int) -> str: ..." in text

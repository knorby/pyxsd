"""Deterministic reports keyed by corpus commit, profile, and case.

Reports contain no timestamps, absolute paths, or set iteration order.  JSON
and TOML are both generated from the same normalized dictionary, so a report
can be regenerated byte-for-byte from checked-in inputs.
"""

from __future__ import annotations

import json
from collections import Counter
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from tests.xslt.outcomes import CaseResult

#: Report document schema version.
REPORT_SCHEMA = 1

_BARE_KEY = set("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-")


def _toml_key(value: str) -> str:
    if value and all(character in _BARE_KEY for character in value):
        return value
    return json.dumps(value, ensure_ascii=False)


def _toml_value(value: Any) -> str:
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, int):
        return str(value)
    return "[" + ", ".join(_toml_value(item) for item in value) + "]"


@dataclass(frozen=True)
class Report:
    """A normalized, deterministic report."""

    corpus: str
    profile: str
    cases: Mapping[str, Mapping[str, Any]]
    schema: int = REPORT_SCHEMA

    def to_dict(self) -> dict[str, Any]:
        cases = {name: dict(self.cases[name]) for name in sorted(self.cases)}
        summary = Counter(entry["outcome"] for entry in cases.values())
        return {
            "schema": self.schema,
            "corpus": self.corpus,
            "profile": self.profile,
            "summary": dict(sorted(summary.items())),
            "cases": cases,
        }


def build_report(results: Iterable[CaseResult], *, corpus: str, profile: str) -> Report:
    """Build one deterministic report from case results."""
    cases: dict[str, dict[str, Any]] = {}
    for result in results:
        if not result.name:
            raise ValueError("a report requires named case results")
        if result.name in cases:
            raise ValueError(f"duplicate case result: {result.name}")
        entry: dict[str, Any] = {
            "outcome": str(result.outcome),
            "coverage": sorted(result.coverage),
            "message": result.message,
        }
        if result.expected_error_code is not None:
            entry["expected_error_code"] = result.expected_error_code
        if result.actual_error_code is not None:
            entry["actual_error_code"] = result.actual_error_code
        cases[result.name] = entry
    return Report(corpus=corpus, profile=profile, cases=cases)


def render_json(report: Report) -> str:
    """Render one report as deterministic JSON with a trailing newline."""
    return json.dumps(report.to_dict(), indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def render_toml(report: Report) -> str:
    """Render one report as deterministic TOML with a trailing newline."""
    document = report.to_dict()
    lines = [
        f"schema = {_toml_value(document['schema'])}",
        f"corpus = {_toml_value(document['corpus'])}",
        f"profile = {_toml_value(document['profile'])}",
        "",
        "[summary]",
    ]
    for outcome, count in document["summary"].items():
        lines.append(f"{_toml_key(outcome)} = {_toml_value(count)}")
    for name, entry in document["cases"].items():
        lines.append("")
        lines.append(f"[cases.{_toml_key(name)}]")
        for key in ("outcome", "coverage", "message", "expected_error_code", "actual_error_code"):
            if key in entry:
                lines.append(f"{key} = {_toml_value(entry[key])}")
    return "\n".join(lines) + "\n"


def write_report(path: Path, report: Report, *, format: str = "json") -> None:
    """Write one report under *path*; the caller chooses a safe directory."""
    if format == "json":
        text = render_json(report)
    elif format == "toml":
        text = render_toml(report)
    else:
        raise ValueError(f"unknown report format: {format!r}")
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))
